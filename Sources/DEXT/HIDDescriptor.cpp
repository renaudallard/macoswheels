const size_t kPIDBlockLen = sizeof(kPIDBlock);

size_t spliceWithPID(const uint8_t *wheel, size_t wheelLen,
                     uint8_t *out, size_t outCap) {
    if (!wheel || !out) return 0;
    if (wheelLen < 2 || wheel[wheelLen - 1] != 0xC0) return 0;
    size_t merged = wheelLen + kPIDBlockLen;
    if (merged > outCap) return 0;
    for (size_t i = 0; i < wheelLen - 1; ++i) out[i] = wheel[i];
    for (size_t i = 0; i < kPIDBlockLen; ++i)
        out[wheelLen - 1 + i] = kPIDBlock[i];
    out[merged - 1] = 0xC0;
    return merged;
}

